'use strict';
const {test,after}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {spawn}=require('node:child_process');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'acr-perms-test-'));
const port=28000+Math.floor(Math.random()*21000);
const url='http://127.0.0.1:'+port;
const key='admin-key-for-permission-test-'+'x'.repeat(35);
const child=spawn(process.execPath,['server.js'],{cwd:path.join(__dirname,'..'),env:{...process.env,PORT:String(port),PUBLIC_BASE_URL:url,ADMIN_KEY:key,DATA_FILE:path.join(dir,'requests.json'),TEAM_DATA_FILE:path.join(dir,'team.json')},stdio:'ignore'});
after(()=>{child.kill();fs.rmSync(dir,{recursive:true,force:true});});
async function ready(){for(let i=0;i<100;i++){try{if((await fetch(url+'/health')).ok)return;}catch{}await new Promise(r=>setTimeout(r,55));}throw Error('Server unavailable');}
async function api(endpoint,method='GET',body,token=''){
 const result=await fetch(url+'/api/team/'+endpoint,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body?JSON.stringify(body):undefined});
 return {status:result.status,data:await result.json()};
}
test('admin configures fine grained permissions; updates revoke old sessions and server enforces access',async()=>{
 await ready();
 let a=await fetch(url+'/api/team/bootstrap',{method:'POST',headers:{'X-API-Key':key,'Content-Type':'application/json'},body:JSON.stringify({nome:'Admin ACR',login:'gestor',senha:'senha-forte'})});
 assert.equal(a.status,201);const admin=(await a.json()).token;
 let u=await api('users','POST',{nome:'Técnico de Teste',login:'teste-tech',perfil:'Técnico',senha:'senha-forte'},admin);
 assert.equal(u.status,200);const uid=u.data.user.id;
 assert.equal(u.data.user.permissions.financeiro,false);
 let t=await api('login','POST',{login:'teste-tech',senha:'senha-forte'});const old=t.data.token;
 assert.equal((await api('workspace','GET',null,old)).status,200);
 assert.equal((await api('users/'+uid+'/permissions','PUT',{permissions:{financeiro:true}},old)).status,403);
 assert.equal((await api('users/'+uid+'/permissions','PUT',{permissions:{admin:true}},admin)).status,400);
 assert.equal((await api('users/'+uid+'/permissions','PUT',{permissions:{financeiro:'sim'}},admin)).status,400);
 const update=await api('users/'+uid+'/permissions','PUT',{permissions:{clientes:false,ordens:false,assinaturas:false,links:false,financeiro:true,relatorios:false}},admin);
 assert.equal(update.status,200);assert.equal(update.data.user.permissions.financeiro,true);
 assert.equal((await api('workspace','GET',null,old)).status,401);
 t=await api('login','POST',{login:'teste-tech',senha:'senha-forte'});
 const current=t.data.token;
 assert.equal(t.data.account.permissions.clientes,false);assert.equal(t.data.account.permissions.financeiro,true);
 const state=await api('workspace','GET',null,current);
 assert.deepEqual(state.data.clients,[]);assert.deepEqual(state.data.orders,[]);
 assert.deepEqual(state.data.finance,[]);
 let put=await api('workspace','PUT',{revision:0,clients:[{id:'x'}],orders:[],drafts:[],finance:[]},current);
 assert.equal(put.status,403);
 put=await api('workspace','PUT',{revision:0,clients:[],orders:[],drafts:[],finance:[{id:'f1',valor:75,tipo:'receita'}]},current);
 assert.equal(put.status,200);
 assert.equal(put.data.revision,1);
 assert.equal((await api('workspace','GET',null,admin)).data.finance.length,1);
 const requestBody={orderNumber:'OS-TEST-1',clientName:'Teste',serviceTitle:'Suporte'};
 a=await fetch(url+'/api/sign-requests',{method:'POST',headers:{'Content-Type':'application/json',Authorization:'Bearer '+current,'X-API-Key':key},body:JSON.stringify(requestBody)});
 assert.equal(a.status,403);
 const promote=await api('users/'+uid+'/permissions','PUT',{permissions:{links:true,clientes:true,ordens:true,assinaturas:true}},admin);
 assert.equal(promote.status,200);assert.equal((await api('me','GET',null,current)).status,401);
 t=await api('login','POST',{login:'teste-tech',senha:'senha-forte'});
 a=await fetch(url+'/api/sign-requests',{method:'POST',headers:{'Content-Type':'application/json',Authorization:'Bearer '+t.data.token},body:JSON.stringify(requestBody)});
 assert.equal(a.status,201);
 const data=JSON.parse(fs.readFileSync(path.join(dir,'team.json')));
 assert.equal(data.accounts.find(x=>x.id===uid).permissions.financeiro,true);
 assert.equal(data.workspace.finance.length,1);
 assert.equal((await api('users/'+(await api('me','GET',null,admin)).data.account.id+'/permissions','PUT',{permissions:{financeiro:false}},admin)).status,403);
});
